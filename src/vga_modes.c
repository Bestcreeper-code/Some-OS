void vga_set_mode(const char gr_mode) {
    const vga_mode* mode;

    switch (gr_mode)
    {
    case 0x03:
        vga_load_font(font8x16, 16);
        mode = &vga_mode_03h;
        break;
    case 0x13:
        mode = &vga_mode_13h;
        Get_multiboot_info()->framebuffer_pitch =320;
        break;
    
    default:
        mode = &vga_mode_03h;//so no crash
        break;
    }

    // 1. Misc register
    outb(0x3C2, mode->misc);

    // 2. Sequencer registers
    for (int i = 0; i < 5; i++) {
        outb(0x3C4, i);
        outb(0x3C5, mode->seq[i]);
    }

    // 3. Unlock CRTC registers
    outb(0x3D4, 0x03);
    outb(0x3D5, inb(0x3D5) | 0x80);
    outb(0x3D4, 0x11);
    outb(0x3D5, inb(0x3D5) & ~0x80);

    // 4. CRTC registers
    for (int i = 0; i < 25; i++) {
        outb(0x3D4, i);
        outb(0x3D5, mode->crtc[i]);
    }

    // 5. Graphics controller registers
    for (int i = 0; i < 9; i++) {
        outb(0x3CE, i);
        outb(0x3CF, mode->gc[i]);
    }

    // 6. Attribute controller registers
    for (int i = 0; i < 21; i++) {
        inb(0x3DA);
        outb(0x3C0, i);
        outb(0x3C0, mode->attr[i]);
    }
    inb(0x3DA);
    outb(0x3C0, 0x20);
}

void vga_load_font(const uint8_t *font, uint16_t height) {
    // 1. Unlock CRTC registers 0x09 and 0x0A (important for font loading)
    outb(0x3D4, 0x11);
    uint8_t val = inb(0x3D5);
    outb(0x3D5, val & 0x7F);  // Clear bit 7 to unlock CRTC registers

    // 1.5 Set character height (CRTC register 0x09)
    outb(0x3D4, 0x09);
    outb(0x3D5, height - 1);  // height in scanlines (e.g., 16 → 0x0F)
    
    // 2. Select plane 2 for CPU writes (Sequencer register 2)
    outb(0x3C4, 0x02);
    outb(0x3C5, 0x04);

    // 3. Disable chain-4 (Sequencer register 4)
    outb(0x3C4, 0x04);
    outb(0x3C5, 0x06);

    // 4. Set graphics controller to write to plane 2 only (Graphics registers 4,5,6)
    outb(0x3CE, 0x04);
    outb(0x3CF, 0x02);
    outb(0x3CE, 0x05);
    outb(0x3CF, 0x00);
    outb(0x3CE, 0x06);
    outb(0x3CF, 0x00);

    // 5. Write font data to VGA memory plane 2 at 0xA0000
    uint8_t *vram = (uint8_t*)0xA0000;
    for (int i = 0; i < 256 ; i++) {
        for (int j = 0; j < height; j++)
        {
            vram[i*2*height + j] = font[i*height + j];
        }
    }

    // 6. Restore sequencer and graphics registers for normal text mode
    // Enable chain-4, odd/even addressing, all planes
    outb(0x3C4, 0x04);
    outb(0x3C5, 0x03);
    outb(0x3C4, 0x02);
    outb(0x3C5, 0x03);

    outb(0x3CE, 0x04);
    outb(0x3CF, 0x00);
    outb(0x3CE, 0x05);
    outb(0x3CF, 0x10);
    outb(0x3CE, 0x06);
    outb(0x3CF, 0x0A);

    // 7. Lock CRTC registers again
    outb(0x3D4, 0x11);
    val = inb(0x3D5);
    outb(0x3D5, val | 0x80);
    
}